"""Render actual benchmark results as readable tables and confusion-matrix plots."""

import os
from pathlib import Path

# Respect an explicit user setting; otherwise keep generated caches inside the project.
os.environ.setdefault('MPLCONFIGDIR', str(Path(__file__).resolve().parents[1] / '.mpl-cache'))
import matplotlib
matplotlib.use('Agg')  # A file-only backend works on laptops and headless CI.
import matplotlib.pyplot as plt
import numpy as np


def write_report(results: dict, output_dir: Path) -> None:
    """Generate every numerical claim from results, keeping limitations explicit."""
    config = results['config']
    lines = [
        '# German Credit — Validation Report', '',
        'Generated by `python -m scripts.benchmark` from actual execution.', '',
        '## Provenance and protocol', '',
        '[UCI Statlog German Credit, ID 144](https://archive.ics.uci.edu/dataset/144/statlog+german+credit+data). '
        'Hofmann (1994), DOI: https://doi.org/10.24432/C5NC77; CC BY 4.0. '
        'See `../data/README.md` for attribution and raw-file provenance.', '',
        f"Input: {results['dataset']['n_samples']} rows, {results['dataset']['n_features']} features. "
        f"SHA-256: `{results['dataset']['sha256']}`.", '',
        'Positive class: bad credit = 1 (original UCI 2); good credit = 0 (original UCI 1).', '',
        f"Seed {config['seed']}; stratified 80/20 split; "
        f"{len(results['split']['train_indices'])} training and "
        f"{len(results['split']['holdout_indices'])} holdout rows. "
        f"Training-only {config['n_splits']}-fold shuffled StratifiedKFold; identical folds for both models.", '',
        f"Train counts (0/1): {results['split']['train_counts']}; "
        f"holdout counts (0/1): {results['split']['holdout_counts']}.", '',
        f"LR: C=1, lbfgs, max_iter=2000. RF: {config['n_trees']} trees, unlimited depth. "
        'Other parameters use the pinned sklearn defaults. No hyperparameter search or holdout-driven selection.', '',
        'Numerical median imputation; LR-only standardization. Categorical most-frequent imputation '
        'and one-hot encoding with unseen categories ignored. All learned preprocessing is fitted '
        'inside each training fold. Final fits use training rows only.', '',
        f"Decision rule: P(bad) >= {config['threshold']}. Precision, recall and F1 treat bad as positive; "
        'ROC-AUC uses P(bad). Undefined precision/F1 are set to zero.', '',
        '## Training-only cross-validation', '',
        'Values are fold mean ± sample standard deviation (ddof=1). Fold variability is not a '
        'confidence interval; folds have overlapping training samples.', '',
        '| Model | Accuracy | Precision | Recall | F1 | ROC-AUC | Mean cost |',
        '|---|---:|---:|---:|---:|---:|---:|',
    ]
    metric_names = ['accuracy', 'precision', 'recall', 'f1', 'roc_auc', 'mean_cost']
    for name, model in results['models'].items():
        values = [f"{model['cv']['summary'][m]['mean']:.4f} ± {model['cv']['summary'][m]['std']:.4f}"
                  for m in metric_names]
        lines.append('| ' + name + ' | ' + ' | '.join(values) + ' |')
    lines += ['', '## Training versus holdout', '',
              'Training scores are resubstitution scores, not independent validation.', '',
              '| Model | Set | Accuracy | Precision | Recall | F1 | ROC-AUC | Mean cost | Total cost |',
              '|---|---|---:|---:|---:|---:|---:|---:|---:|']
    for name, model in results['models'].items():
        for partition in ['train', 'holdout']:
            score = model[partition]
            values = [f'{score[m]:.4f}' for m in metric_names]
            lines.append(f'| {name} | {partition} | ' + ' | '.join(values) + f" | {score['total_cost']} |")
    lines += ['', '## Errors, costs and possible overfitting', '',
              'Confusion matrices use actual rows and predicted columns, both ordered [good, bad]: '
              '`[[TN, FP], [FN, TP]]`.', '',
              'UCI benchmark cost = FP + 5×FN; correct predictions cost zero. Mean cost = total / rows. '
              'These are relative benchmark units, not dollars or real-world bank losses. '
              'The 0.5 threshold is a fixed classification baseline, not a cost-optimal policy. '
              'A theoretical 1/6 cost threshold assumes calibrated probabilities and applicable costs; '
              'neither is established here. No threshold was selected on holdout data.', '']
    figure, axes = plt.subplots(1, len(results['models']), figsize=(9, 4))
    for axis, (name, model) in zip(np.atleast_1d(axes), results['models'].items()):
        holdout = model['holdout']
        matrix = np.array(holdout['confusion_matrix'])
        tn, fp, fn, tp = matrix.ravel()
        gap = model['train']['roc_auc'] - holdout['roc_auc']
        lines += [f'### {name}', '',
                  f'Holdout matrix: `{matrix.tolist()}`. False negatives: {fn}; false positives: {fp}. '
                  f'Cost contributions: missed bad risks {5 * fn}, good risks flagged bad {fp}.', '',
                  f'Train minus holdout ROC-AUC gap: {gap:.4f}. '
                  + ('The positive gap is consistent with possible overfitting, but one split cannot establish its cause.'
                     if gap > 0 else 'This split does not show a positive ROC-AUC generalization gap.'), '']
        axis.imshow(matrix, cmap='Blues', vmin=0, vmax=len(results['split']['holdout_indices']))
        for row in range(2):
            for column in range(2):
                axis.text(column, row, str(matrix[row, column]), ha='center', va='center')
        axis.set(xticks=[0, 1], yticks=[0, 1], xticklabels=['Good (0)', 'Bad (1)'],
                 yticklabels=['Good (0)', 'Bad (1)'], xlabel='Predicted', ylabel='Actual', title=name)
    figure.tight_layout()
    figure.savefig(output_dir / 'confusion_matrices.png', dpi=150)
    plt.close(figure)
    lines += ['![Holdout confusion matrices](confusion_matrices.png)', '',
              '### Constant holdout baselines', '',
              '| Rule | Accuracy | Bad recall | Total cost | Mean cost |',
              '|---|---:|---:|---:|---:|']
    for name, score in results['baselines'].items():
        lines.append(f"| {name} | {score['accuracy']:.4f} | {score['recall']:.4f} | "
                     f"{score['total_cost']} | {score['mean_cost']:.4f} |")
    always_bad_cost = results['baselines']['always_bad']['total_cost']
    worse_than_constant = [name for name, model in results['models'].items()
                           if model['holdout']['total_cost'] > always_bad_cost]
    if worse_than_constant:
        lines += ['', 'At the fixed threshold, ' + ' and '.join(worse_than_constant)
                  + ' have higher holdout benchmark cost than always predicting bad. '
                  'This is a failure of these fixed decision rules under the supplied costs, '
                  'not a recommendation to reject every applicant. Accuracy alone misses this tradeoff.']
    lines += ['', '## Limitations and next validation steps', '',
              '- Small historical German credit sample; donated in 1994, with legacy Deutsche Mark '
              'categories. Modern Canadian credit decisions and populations may differ.',
              '- Random splitting cannot validate future-time or new-institution performance. '
              'Row separation does not prove person-level independence; no reliable grouping/time '
              'metadata is used here.',
              '- Personal status/sex, age and foreign-worker fields raise fairness and proxy concerns. '
              'No subgroup fairness, legal compliance, probability calibration or drift evaluation '
              'was completed; removing a field alone would not establish fairness.',
              '- No missing values in this official snapshot; synthetic missing-value tests only verify '
              'pipeline mechanics. They do not demonstrate robustness to real missingness.',
              '- Aggregate errors identify missed bad risks and good risks flagged bad. '
              'They do not explain individual causes. Predictions and row IDs are saved for follow-up analysis.',
              '- CV spread and the holdout provide limited evidence from one dataset and one fixed split. '
              'Future tuning must stay inside training data; repeated decisions based on this holdout '
              'would require a new independent final evaluation.',
              '- Educational classical tabular benchmark only: no TD proprietary data, no clinical or '
              'production suitability claim, and not validation of deep learning foundation models.', '',
              '## Reproduction artifacts', '',
              '`benchmark_results.json` records environment, settings, split/fold row IDs and all metrics. '
              '`holdout_predictions.csv` records actual labels, positive probabilities and predictions. '
              'The report and image are generated from those execution results.', '']
    (output_dir / 'validation_report.md').write_text('\n'.join(lines), encoding='utf-8')
